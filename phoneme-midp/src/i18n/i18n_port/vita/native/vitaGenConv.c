/*
 * vitaGenConv.c - generic byte<->Unicode converter for J2ME charsets.
 *
 * Why
 * ---
 * phoneME Feature's i18n port has no generic converter: the upstream
 * "default" implementation returns NULL from getLcGenConvMethods(), so
 * every charset that is not compiled in as its own Java class
 * (ISO8859_1, UTF_8/16) fails with UnsupportedEncodingException.  J2ME
 * games do use them: `new InputStreamReader(in, "SJIS")` while loading a
 * Japanese resource, `String.getBytes("GBK")` when saving a Chinese high
 * score, EUC-KR text in Korean builds, Big5 in Taiwanese builds.
 *
 * What
 * ----
 * This file implements the one hook the MIDP i18n layer is designed
 * around (conv.h): getLcGenConvMethods(encoding) returns a function set
 * that conv.c then calls from the KNI entry points of
 * com.sun.cldc.i18n.j2me.Gen_Reader / Gen_Writer.  No Java code is
 * touched; the byte<->Unicode tables live in vita_charmap.h, generated by
 * tools/charsetgen/gen_charmap.py.
 *
 * Contract (from conv.c and Gen_Reader/Gen_Writer):
 *   byteLen(b,len)           1/2 = length of one character,
 *                            0 = invalid byte, -1 = needs one more byte
 *   nativeToUnicode           writes up to outLen jchars, returns count;
 *                            an invalid byte becomes U+FFFD and is skipped
 *   unicodeToNative           returns bytes written; unmappable characters
 *                            become '?' (one byte) so the stream stays
 *                            decodable instead of throwing
 *   sizeOfByteInUnicode       characters (an invalid byte counts as one)
 *   sizeOfUnicodeInByte       bytes
 *
 * The offset arguments of the sizeOf* hooks are ignored on purpose:
 * conv.c copies the requested window into a private buffer and passes
 * (buf, offset, length) - the window is already offset (see conv.c
 * Java_..._sizeOfByteInUnicode).
 *
 * Build wiring: i18n_port/vita/lib.gmk adds this file when
 * USE_I18N_VITA=true (phoneme-midp/build/vita_arm/Settings.gmk).
 */
#include <stddef.h>

#include <kni.h>
#include <conv.h>

#include "vita_charmap.h"

/* Unicode -> native code (0x00XX = one byte, 0xXXXX = two bytes); 0 = none */
static unsigned int vita_rev_lookup(const vita_charmap *m, unsigned short cp) {
    int lo = 0;
    int hi = (int)m->rev_n - 1;

    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        unsigned int v = m->rev[mid];
        unsigned int vcp = v >> 16;

        if (vcp < cp) {
            lo = mid + 1;
        } else if (vcp > cp) {
            hi = mid - 1;
        } else {
            return v & 0xFFFF;
        }
    }
    return 0;
}

/* Encoding names arrive from Java; be liberal: case-insensitive and
 * ignoring '-', '_' and spaces ("Shift_JIS" == "Shift-JIS" == "SJIS"? no,
 * but "EUC-JP" == "EUC_JP" and "euckr" == "EUC-KR" do). */
static int vita_name_eq(const char *a, const char *b) {
    while (*a != 0 && *b != 0) {
        char ca = *a;
        char cb = *b;

        if (ca >= 'A' && ca <= 'Z') ca = (char)(ca - 'A' + 'a');
        if (cb >= 'A' && cb <= 'Z') cb = (char)(cb - 'A' + 'a');
        if (ca == '-' || ca == '_' || ca == ' ') { a++; continue; }
        if (cb == '-' || cb == '_' || cb == ' ') { b++; continue; }
        if (ca != cb) {
            return 0;
        }
        a++;
        b++;
    }
    while (*a == '-' || *a == '_' || *a == ' ') a++;
    while (*b == '-' || *b == '_' || *b == ' ') b++;
    return *a == 0 && *b == 0;
}

/* Decode one character.  Returns its byte length (1 or 2), 0 for an
 * invalid byte, or -1 when one more byte is needed to decide. */
static int vc_charBytes(const vita_charmap *m, const unsigned char *b, int len,
                        unsigned int *cp) {
    unsigned char c;
    int blk;

    if (len <= 0) {
        return 0;
    }
    c = b[0];
    if (c == 0) {                 /* NUL is valid but has no table entry */
        *cp = 0;
        return 1;
    }
    if (m->sb[c] != 0) {
        *cp = m->sb[c];
        return 1;
    }
    blk = m->hi[c];
    if (blk != 0) {               /* known lead byte */
        if (len < 2) {
            return -1;
        }
        if (m->db[(blk - 1) * 256 + b[1]] != 0) {
            *cp = m->db[(blk - 1) * 256 + b[1]];
            return 2;
        }
        return 0;                 /* lead byte with an invalid trail */
    }
    if (c >= 0x80) {              /* unassigned high byte: 1 byte if we */
        return (len < 2) ? -1 : 0; /* cannot even tell yet */
    }
    return 0;
}

static int vc_byteLen(const vita_charmap *m, const unsigned char *b, int len) {
    unsigned int cp;
    return vc_charBytes(m, b, len, &cp);
}

static int vc_nativeToUnicode(const vita_charmap *m, const unsigned char *in,
                              int inLen, jchar *out, int outLen) {
    int i = 0;
    int o = 0;

    while (i < inLen && o < outLen) {
        unsigned int cp;
        int n = vc_charBytes(m, in + i, inLen - i, &cp);

        if (n == 1) {
            out[o++] = (jchar)cp;
            i += 1;
        } else if (n == 2) {
            out[o++] = (jchar)cp;
            i += 2;
        } else if (n < 0) {
            break;                /* truncated tail: leave it to the caller */
        } else {
            out[o++] = (jchar)0xFFFD;
            i += 1;
        }
    }
    return o;
}

static int vc_unicodeToNative(const vita_charmap *m, const jchar *in,
                              int inLen, unsigned char *out, int outLen) {
    int i;
    int o = 0;

    for (i = 0; i < inLen; i++) {
        unsigned int code = vita_rev_lookup(m, (unsigned short)in[i]);

        if (code == 0) {          /* not representable: '?' keeps it 1 byte */
            if (o + 1 > outLen) {
                break;
            }
            out[o++] = '?';
        } else if (code <= 0xFF) {
            if (o + 1 > outLen) {
                break;
            }
            out[o++] = (unsigned char)code;
        } else {
            if (o + 2 > outLen) {
                break;
            }
            out[o++] = (unsigned char)(code >> 8);
            out[o++] = (unsigned char)(code & 0xFF);
        }
    }
    return o;
}

static int vc_sizeOfByteInUnicode(const vita_charmap *m, const unsigned char *b,
                                  int len) {
    int i = 0;
    int n = 0;

    while (i < len) {
        unsigned int cp;
        int k = vc_charBytes(m, b + i, len - i, &cp);

        if (k == 1) {
            i += 1;
            n += 1;
        } else if (k == 2) {
            i += 2;
            n += 1;
        } else if (k < 0) {
            break;
        } else {
            i += 1;
            n += 1;
        }
    }
    return n;
}

static int vc_sizeOfUnicodeInByte(const vita_charmap *m, const jchar *c,
                                  int len) {
    int i;
    int o = 0;

    for (i = 0; i < len; i++) {
        unsigned int code = vita_rev_lookup(m, (unsigned short)c[i]);
        o += (code == 0 || code <= 0xFF) ? 1 : 2;
    }
    return o;
}

/* One thin wrapper set per encoding: LcConvMethodsRec has no user data,
 * so every table needs its own six functions. */
#define DEFINE_CONV(TAG, IDX, ENCNAME)                                        \
static int TAG##_byteMaxLen(void) { return 2; }                               \
static int TAG##_byteLen(const unsigned char *b, int n)                       \
{ return vc_byteLen(&vita_charmaps[IDX], b, n); }                             \
static int TAG##_nat2uni(const unsigned char *in, int n, jchar *o, int on)     \
{ return vc_nativeToUnicode(&vita_charmaps[IDX], in, n, o, on); }             \
static int TAG##_uni2nat(const jchar *in, int n, unsigned char *o, int on)     \
{ return vc_unicodeToNative(&vita_charmaps[IDX], in, n, o, on); }             \
static int TAG##_sbiu(const unsigned char *b, int off, int n)                 \
{ (void)off; return vc_sizeOfByteInUnicode(&vita_charmaps[IDX], b, n); }      \
static int TAG##_siub(const jchar *c, int off, int n)                         \
{ (void)off; return vc_sizeOfUnicodeInByte(&vita_charmaps[IDX], c, n); }      \
static LcConvMethodsRec TAG##ConvRec = {                                      \
    (char *)ENCNAME, TAG##_byteMaxLen, TAG##_byteLen, TAG##_uni2nat,           \
    TAG##_nat2uni, TAG##_sbiu, TAG##_siub                                     \
}

DEFINE_CONV(sjis, 0, "SJIS");
DEFINE_CONV(eucjp, 1, "EUC-JP");
DEFINE_CONV(euckr, 2, "EUC-KR");
DEFINE_CONV(gbk, 3, "GBK");
DEFINE_CONV(big5, 4, "Big5");

static LcConvMethods const vita_convs[] = {
    &sjisConvRec,
    &eucjpConvRec,
    &euckrConvRec,
    &gbkConvRec,
    &big5ConvRec
};

#define VITA_CONV_COUNT (int)(sizeof(vita_convs) / sizeof(vita_convs[0]))

/*
 * The hook conv.c calls for encodings it does not know.  NULL means
 * "not supported", which Gen_Reader/Gen_Writer turn into
 * UnsupportedEncodingException - exactly the behaviour a game expects
 * for an encoding we really do not have.
 */
LcConvMethods getLcGenConvMethods(char *encoding) {
    int i;
    int j;

    if (encoding == NULL || *encoding == 0) {
        return NULL;
    }
    for (i = 0; i < VITA_CONV_COUNT; i++) {
        const char *const *names = vita_charmaps[i].names;

        for (j = 0; names[j] != NULL; j++) {
            if (vita_name_eq(encoding, names[j])) {
                return vita_convs[i];
            }
        }
    }
    return NULL;
}


